"""creates a list of fruit before applying multiplel list methods, printing the present state of the list each time"""
fruit = ["cherry", "strawberry", "melon", "grape", "apple"]

# Sort list
fruit.sort()
print(fruit)
# Reverse order of list items
fruit.reverse()
print(fruit)
# Remove all items
fruit.clear()
print(fruit)